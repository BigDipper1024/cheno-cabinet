function startBusinessTypewriter() {
  const node = $("#businessText");
  if (!node) return;

  const text = i18n[state.lang].heroText;
  window.clearTimeout(state.typewriterTimer);
  node.textContent = "";
  node.classList.add("is-typing");

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    node.textContent = text;
    node.classList.remove("is-typing");
    return;
  }

  let index = 0;
  const step = () => {
    node.textContent = text.slice(0, index);
    index += 1;
    if (index <= text.length) {
      state.typewriterTimer = window.setTimeout(step, state.lang === "zh" ? 42 : 24);
    } else {
      node.classList.remove("is-typing");
    }
  };
  step();
}

function updateUploadStatus() {
  const count = state.images.length;
  if (!count) {
    $("#uploadStatus").textContent = i18n[state.lang].uploadStatus;
    return;
  }
  if (state.lang === "zh") {
    $("#uploadStatus").textContent = `${count} ${i18n.zh.uploadReady}`;
  } else if (state.lang === "fr") {
    $("#uploadStatus").textContent = `${count} ${count === 1 ? "photo prête" : i18n.fr.uploadReady}`;
  } else {
    $("#uploadStatus").textContent = `${count} ${count === 1 ? "photo ready for this case" : i18n.en.uploadReady}`;
  }
}

