function generateCopy() {
  const data = projectData();
  const style = currentStyle();
  state.copy = copyBlocks(data, style);
  $("#copyZh").textContent = state.copy.zh;
  $("#copyEn").textContent = state.copy.en;
  $("#copyFr").textContent = state.copy.fr;
  updatePreview();
}

function fieldValue(id) {
  return $(`#${id}`)?.value.trim() || "";
}

function messageSubject(name, area) {
  const safeName = name || "New customer";
  const safeArea = area || "Area not specified";
  return `Cheno cabinet inquiry - ${safeName} - ${safeArea}`;
}

function messageBody() {
  const labels = i18n[state.lang];
  const values = {
    name: fieldValue("guestName"),
    contact: fieldValue("guestContact"),
    area: fieldValue("guestArea"),
    projectType: fieldValue("guestProjectType"),
    timeline: fieldValue("guestTimeline"),
    notes: fieldValue("guestNotes")
  };

  return [
    "Hello Cheno cabinet,",
    "",
    "I would like to ask about a kitchen / cabinet project.",
    "",
    `${labels.guestName}: ${values.name}`,
    `${labels.guestContact}: ${values.contact}`,
    `${labels.guestArea}: ${values.area}`,
    `${labels.guestProjectType}: ${values.projectType}`,
    `${labels.guestTimeline}: ${values.timeline || "-"}`,
    `${labels.guestNotes}: ${values.notes || "-"}`,
    "",
    "Please contact me when available.",
    "",
    "Thank you."
  ].join("\n");
}

function handleMessageSubmit(event) {
  event.preventDefault();

  const form = event.currentTarget;
  if (!form.checkValidity()) {
    form.reportValidity();
    return;
  }

  const name = fieldValue("guestName");
  const area = fieldValue("guestArea");
  const subject = encodeURIComponent(messageSubject(name, area));
  const body = encodeURIComponent(messageBody());
  window.location.href = `mailto:${contactEmail}?subject=${subject}&body=${body}`;
  $("#messageStatus").textContent = i18n[state.lang].messageReady;
}

async function copyText(text, message) {
  try {
    await navigator.clipboard.writeText(text);
    $("#copyStatus").textContent = message;
    window.setTimeout(() => {
      $("#copyStatus").textContent = "";
    }, 1800);
  } catch {
    $("#copyStatus").textContent = i18n[state.lang].copyFailed;
  }
}

function bindEvents() {
  $$(".lang-btn").forEach((button) => {
    button.addEventListener("click", () => applyLanguage(button.dataset.lang));
  });

  $("#photoInput").addEventListener("change", (event) => readFiles(event.target.files));

  const uploadZone = $("#uploadZone");
  ["dragenter", "dragover"].forEach((eventName) => {
    uploadZone.addEventListener(eventName, (event) => {
      event.preventDefault();
      uploadZone.classList.add("is-dragging");
    });
  });
  ["dragleave", "drop"].forEach((eventName) => {
    uploadZone.addEventListener(eventName, (event) => {
      event.preventDefault();
      uploadZone.classList.remove("is-dragging");
    });
  });
  uploadZone.addEventListener("drop", (event) => readFiles(event.dataTransfer.files));

  Object.values(fields).forEach((input) => {
    input.addEventListener("input", () => {
      generateCopy();
    });
  });

  $("#generateBtn").addEventListener("click", () => {
    generateCopy();
    $("#copy").scrollIntoView({ behavior: "smooth", block: "start" });
  });

  $$("[data-copy]").forEach((button) => {
    button.addEventListener("click", () => {
      const lang = button.dataset.copy;
      copyText(state.copy[lang] || "", i18n[state.lang].copied);
    });
  });

  $("#copyAllBtn").addEventListener("click", () => {
    const all = `中文\n${state.copy.zh}\n\nEnglish\n${state.copy.en}\n\nFrançais\n${state.copy.fr}`;
    copyText(all, i18n[state.lang].copiedAll);
  });

  $("#messageForm").addEventListener("submit", handleMessageSubmit);
}

renderStyles();
