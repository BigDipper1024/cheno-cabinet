function currentStyle() {
  return styles.find((style) => style.id === state.styleId) || styles[0];
}

function applyOwnerMode() {
  document.body.classList.toggle("owner-mode", state.ownerMode);
  document.body.classList.toggle("public-mode", !state.ownerMode);
  if (!state.ownerMode && (window.location.hash === "#owner" || window.location.hash === "#copy")) {
    window.history.replaceState(null, "", `${window.location.pathname}${window.location.search}#showcase`);
  }
}

function applyLanguage(lang) {
  state.lang = lang;
  document.documentElement.lang = lang === "zh" ? "zh-CN" : lang === "fr" ? "fr" : "en";
  $$("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = i18n[lang][key] || i18n.zh[key] || node.textContent;
  });
  $$("[data-aria-key]").forEach((node) => {
    const key = node.dataset.ariaKey;
    node.setAttribute("aria-label", i18n[lang][key] || i18n.zh[key] || node.getAttribute("aria-label"));
  });
  $$(".lang-btn").forEach((button) => {
    const active = button.dataset.lang === lang;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
  updateUploadStatus();
  startBusinessTypewriter();
  updatePreview();
}

function renderStyles() {
  const grid = $("#styleGrid");
  grid.innerHTML = "";
  styles.forEach((style) => {
    const button = document.createElement("button");
    button.className = "style-option";
    button.type = "button";
    button.dataset.style = style.id;
    button.innerHTML = `
      <span class="swatch" style="background:${style.swatch}"></span>
      <span>
        <strong>${style.name}</strong>
        <small>${style.note}</small>
      </span>
    `;
    button.addEventListener("click", () => {
      state.styleId = style.id;
      renderStyles();
      updatePreview();
      generateCopy();
    });
    grid.appendChild(button);
  });
  $$(".style-option").forEach((button) => {
    const active = button.dataset.style === state.styleId;
    button.classList.toggle("is-active", active);
    button.setAttribute("aria-pressed", String(active));
  });
}

function escapeText(text) {
  return String(text || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

